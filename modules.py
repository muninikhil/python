import math
import random
print (math.sqrt(166)) #printing the square root of 16
print (math.ceil(4.2)) #printing the ceiling of 4.2
print (math.floor(4.8)) #printing the floor of 4.8
print (math.factorial(5)) #printing the factorial of 5
print (math.gcd(12, 15)) #printing the greatest common divisor of 12 and 15
print (math.sin(math.pi/2)) #printing the sine of pi/2
print (math.cos(math.pi)) #printing the cosine of pi
print (math.tan(math.radians(45))) #printing the tangent of 45 degrees
print (math.log(100, 10)) #printing the logarithm of 100 to base 10 
print (math.exp(2)) #printing the exponential of 2
print (math.pow(2, 3)) #printing 2 raised to the power of 3
print (math.isqrt(16)) #printing the integer square root of 16
print (math.fsum([1.1, 2.2, 3.3])) #printing the sum of the floating point numbers in the list  
print (math.prod([1, 2, 3, 4])) #printing the product of the numbers in the list

print (random.randint(1, 10)) #printing a random integer between 1 and 10   
print (random.random()) #printing a random float between 0 and 1
print (random.choice(['apple', 'banana', 'cherry'])) #printing a random element from the list   